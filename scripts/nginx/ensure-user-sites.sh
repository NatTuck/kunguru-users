#!/usr/bin/env bash
# ensure-user-sites.sh  (run as root on the gateway, via the app transport)
#
# Renders the gateway's nginx routes for account apps and static sites, then
# reloads nginx. Driven by the app:
#
#   KUNGURU_BASE_DOMAIN  e.g. example.com
#   KUNGURU_ROUTES       JSON array of {hostname, upstream, slot} to proxy
#   KUNGURU_LOCAL_SITES  JSON array of {hostname, label, owner, root}: static
#                        sites owned on THIS host, served from a docroot
#   KUNGURU_SITES_CERT   cert name (default kunguru-sites)
#   KUNGURU_AUTH_TARGET  the app's /internal/auth: `host:port` (loopback) or
#                        `unix:/path/to/auth.sock`
#   KUNGURU_AUTH_HOST    login app host (default users.<base>)
#
# Hosts (see server/sites.ts):
#   <account>.<base>          app         12000+id
#   <account>-dev.<base>      app-dev     13000+id
#   <account>-agent.<base>    webui       11000+id  (always requires auth)
#   <label>.<base>            static      -> <owner-host>:14000
#
# Every routed host goes through the same vhost: the app's /internal/auth
# subrequest decides whether the host is optional-auth or require_auth (and
# whether the session user may use it), and nginx injects the verified
# Remote-User / Remote-Groups headers. The session cookie is stripped before
# proxying.
#
# Static sites owned on this host (the gateway is also a user server for its
# own accounts) are served from their docroot here, NOT through a loopback
# listener: a loopback listener would let any local process read a require_auth
# site by sending the Host header directly.
#
# The certificate is NOT managed here. It is the fixed wildcard pair
# (*.<base>) issued once and renewed by certbot.timer -- see scripts/nginx/acme/.
# This script only renders vhosts, so adding accounts or sites never re-issues a
# certificate.
set -euo pipefail

: "${KUNGURU_BASE_DOMAIN:?missing KUNGURU_BASE_DOMAIN}"
routes_json="${KUNGURU_ROUTES:-[]}"
local_json="${KUNGURU_LOCAL_SITES:-[]}"
cert_name="${KUNGURU_SITES_CERT:-kunguru-sites}"
apex_cert="${KUNGURU_APEX_CERT:-$base}"
auth_target="${KUNGURU_AUTH_TARGET:-127.0.0.1:3030}"

base="$KUNGURU_BASE_DOMAIN"
auth_host="${KUNGURU_AUTH_HOST:-users.${base}}"
webroot="/var/www/certbot"
map_conf="/etc/nginx/conf.d/kunguru-user-sites-map.conf"
site_name="kunguru-user-sites"
site="/etc/nginx/sites-available/${site_name}"
site_link="/etc/nginx/sites-enabled/${site_name}"
cert_dir="/etc/letsencrypt/live/${cert_name}"

command -v nginx >/dev/null || { echo "nginx not installed" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 required" >&2; exit 1; }
mkdir -p "$webroot"

# Strip the session cookie before proxying to tenant apps; the gateway injects
# Remote-User/Remote-Groups instead. Reference copy:
# scripts/nginx/session-cookie-map.conf (also embedded by ensure-nginx.sh).
cat > /etc/nginx/conf.d/kunguru-session-cookie.conf <<'SESSION_MAP'
map $http_cookie $kunguru_cookie_1 {
    default $http_cookie;
    "~^(?<kunguru_pre>.*?)(?:;\s*)?kunguru_sid=[^;]*(?<kunguru_post>;.*)?$" "$kunguru_pre$kunguru_post";
}
map $kunguru_cookie_1 $kunguru_cookie {
    "~^;\s*(?<kunguru_rest>.*)$" $kunguru_rest;
    default $kunguru_cookie_1;
}
SESSION_MAP

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

python3 - "$routes_json" "$local_json" "$base" "$cert_name" "$auth_target" "$auth_host" "$tmp" "$apex_cert" <<'PY'
import json, os, re, sys

routes_json, local_json, base, cert_name, auth_target, auth_host, tmp, apex_cert = sys.argv[1:9]

# nginx wants `http://host:port/uri` or `http://unix:/path:/uri`.
if auth_target.startswith("unix:"):
    auth_pass = "http://unix:{}:/internal/auth".format(auth_target[5:])
else:
    auth_pass = "http://{}/internal/auth".format(auth_target)
webroot = "/var/www/certbot"
cert_dir = "/etc/letsencrypt/live/" + cert_name
apex_cert_dir = "/etc/letsencrypt/live/" + apex_cert
LABEL = r"[a-z][a-z0-9-]*"
HOST_RE = re.compile(r"[a-z0-9.-]+")
UPSTREAM_RE = re.compile(r"[A-Za-z0-9.:\[\]]+")


def parse(raw):
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return []


# Routes are rendered into a `map`, one `host upstream;` line each. Hostnames
# and upstreams are generated by the app, but validate anyway: this text is
# parsed by nginx as root.
routes = []
for r in parse(routes_json):
    host = str(r.get("hostname") or "")
    upstream = str(r.get("upstream") or "")
    if not host or not upstream:
        continue
    if not HOST_RE.fullmatch(host) or not UPSTREAM_RE.fullmatch(upstream):
        print("warning: refusing route with unsafe host/upstream: %r" % (r,), file=sys.stderr)
        continue
    routes.append({"hostname": host, "upstream": upstream})

# Static sites owned on this host: serve the docroot directly. The path must be
# exactly the owner's ~/www/<label>, so a bad DB row can never turn into an
# arbitrary `root` directive.
local = []
for s in parse(local_json):
    owner = str(s.get("owner") or "")
    label = str(s.get("label") or "")
    host = str(s.get("hostname") or "")
    root = str(s.get("root") or "")
    if not re.fullmatch(LABEL, owner) or not re.fullmatch(LABEL, label):
        print("warning: refusing local site with unsafe owner/label: %r" % (s,), file=sys.stderr)
        continue
    # Must live under the owner's ~/www/, with no characters that could break
    # out of the `root` directive.
    prefix = "/home/{}/www/".format(owner)
    if (
        not root.startswith(prefix)
        or len(root) == len(prefix)
        or ".." in root
        or any(c in root for c in " \t\r\n;{}\"'\\")
    ):
        print("warning: refusing local site with unexpected docroot: %r" % (s,), file=sys.stderr)
        continue
    if not HOST_RE.fullmatch(host):
        print("warning: refusing local site with unsafe hostname: %r" % (s,), file=sys.stderr)
        continue
    local.append({"hostname": host, "root": root, "apex": bool(s.get("apex"))})

hosts = sorted({r["hostname"] for r in routes} | {s["hostname"] for s in local})

map_lines = [
    "# Managed by kunguru-users (scripts/nginx/ensure-user-sites.sh).",
    "map $host $kunguru_upstream {",
    "    hostnames;",
    '    default "";',
]
for r in routes:
    map_lines.append("    {} {};".format(r["hostname"], r["upstream"]))
map_lines.append("}")
# WebSocket-capable proxying: `Connection` must be empty (not "close") for
# keepalive/SSE requests, and "upgrade" when the client asks to upgrade.
map_lines += [
    "",
    "map $http_upgrade $kunguru_connection {",
    "    default upgrade;",
    '    ""      "";',
    "}",
]
open(os.path.join(tmp, "map.conf"), "w").write("\n".join(map_lines) + "\n")
open(os.path.join(tmp, "hosts.txt"), "w").write("\n".join(hosts) + ("\n" if hosts else ""))

header = "# Managed by kunguru-users (scripts/nginx/ensure-user-sites.sh).\n"

http_server = """server {{
    listen 80;
    listen [::]:80;
    server_name {base} www.{base} *.{base};

    location /.well-known/acme-challenge/ {{ root {webroot}; }}
    location / {{ return 301 https://$host$request_uri; }}
}}
""".format(base=base, webroot=webroot)

auth_location = """    location = /__auth {{
        internal;
        proxy_pass {auth_pass};
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header X-Original-Host $host;
    }}
""".format(auth_pass=auth_pass)

login_location = """    error_page 401 = @login;
    location @login {{
        # `next` is not URL-encoded: a query string with `&` loses its extra
        # parameters here (they become siblings of `next`). The login page
        # still returns to the path, which is the common case.
        return 302 https://{auth_host}/login?next=$scheme://$host$request_uri;
    }}
""".format(auth_host=auth_host)

proxy_body = """    location / {
        auth_request /__auth;
        auth_request_set $auth_user $upstream_http_x_auth_user;
        auth_request_set $auth_groups $upstream_http_x_auth_groups;
        auth_request_set $kunguru_identity $upstream_http_x_auth_jwt;
        if ($kunguru_upstream = "") { return 404; }
        proxy_pass http://$kunguru_upstream;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Remote-User $auth_user;
        proxy_set_header Remote-Groups $auth_groups;
        proxy_set_header X-Kunguru-Identity $kunguru_identity;
        proxy_set_header Cookie $kunguru_cookie;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $kunguru_connection;
        proxy_http_version 1.1;
        proxy_buffering off;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        client_max_body_size 64m;
    }
"""


def https_server(names, body, cert=None):
    return """server {{
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name {names};

    ssl_certificate     {cert_dir}/fullchain.pem;
    ssl_certificate_key {cert_dir}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    server_tokens off;

    # The gateway authenticates every routed host (optionally), injects the
    # verified identity, and strips the session cookie. Hosts marked
    # require_auth get a 401 here and are redirected to the login page.
{auth}
{body}
{login}}}
""".format(
        names=names, cert_dir=cert or cert_dir, auth=auth_location, body=body, login=login_location
    )


def local_body(root):
    return """    location / {{
        auth_request /__auth;
        root {root};
        index index.html index.htm;
        autoindex off;
        disable_symlinks on;
        try_files $uri $uri/index.html =404;
    }}
""".format(root=root)


servers = [https_server("*.{}".format(base), proxy_body)]
for s in local:
    names = s["hostname"]
    cert = None
    if s.get("apex"):
        names = "{} www.{}".format(base, base)
        cert = apex_cert_dir
    servers.append(https_server(names, local_body(s["root"]), cert))
# A remote apex site (owned on a user server) is forwarded through the map like
# any routed host, but needs the base-domain certificate and its own server
# block: the wildcard `*.{base}` does not match the bare domain.
if any(r["hostname"] in (base, "www.{}".format(base)) for r in routes):
    if os.path.isfile(os.path.join(apex_cert_dir, "fullchain.pem")) and os.path.isfile(
        os.path.join(apex_cert_dir, "privkey.pem")
    ):
        servers.append(
            https_server("{} www.{}".format(base, base), proxy_body, apex_cert_dir)
        )
    else:
        print(
            "warning: no certificate at {}; apex site not rendered".format(apex_cert_dir),
            file=sys.stderr,
        )

open(os.path.join(tmp, "sites-http.conf"), "w").write(header + http_server)
open(os.path.join(tmp, "sites-full.conf"), "w").write(
    header + http_server + "\n" + "\n".join(servers)
)
PY

install -m 0644 "$tmp/map.conf" "$map_conf"

hosts_count="$(wc -l < "$tmp/hosts.txt" | tr -d ' ')"
if [[ "$hosts_count" -eq 0 ]]; then
  # No enabled accounts with hosts and no static sites: drop the vhost entirely.
  rm -f "$site_link"
  nginx -t && systemctl reload nginx
  echo "[ok] no account or static-site routes; removed ${site_name}"
  exit 0
fi

# The certificate is the fixed wildcard pair (*.<base>) issued once and renewed
# by certbot.timer (see scripts/nginx/acme/). Render the HTTPS vhost when it is
# present; otherwise fall back to HTTP-only so the app stays reachable while the
# operator issues it.
if [[ -f "${cert_dir}/fullchain.pem" && -f "${cert_dir}/privkey.pem" ]]; then
  rendered="$tmp/sites-full.conf"
  note="gateway routes reconciled (${hosts_count} hostnames, cert ${cert_name})"
else
  rendered="$tmp/sites-http.conf"
  note="warning: no certificate at ${cert_dir}; serving HTTP only -- run scripts/nginx/acme/ensure-sites-cert.sh"
fi

had_site=0
if [[ -f "$site" ]]; then
  cp -a "$site" "$tmp/sites.bak"
  had_site=1
fi
install -m 0644 "$rendered" "$site"
[[ -e "$site_link" ]] || ln -s "$site" "$site_link"

# Never leave a rejected config on disk: the next reload (certbot's deploy
# hook, a reboot) would trip over it. Restore the previous vhost and fail.
if ! nginx -t; then
  if (( had_site )); then
    cp -a "$tmp/sites.bak" "$site"
    echo "error: nginx rejected the rendered routes; restored the previous ${site}" >&2
  else
    rm -f "$site" "$site_link"
    echo "error: nginx rejected the rendered routes; removed ${site}" >&2
  fi
  exit 1
fi
systemctl reload nginx
echo "[ok] ${note}"
